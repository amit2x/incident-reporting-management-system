<?php

// app/Exports/Sheets/KpiSummarySheet.php

namespace App\Exports\Sheets;

use Maatwebsite\Excel\Concerns\FromArray;
use Maatwebsite\Excel\Concerns\WithTitle;
use Maatwebsite\Excel\Concerns\WithStyles;
use Maatwebsite\Excel\Concerns\ShouldAutoSize;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;
use PhpOffice\PhpSpreadsheet\Style\Fill;

class KpiSummarySheet implements FromArray, WithTitle, WithStyles, ShouldAutoSize
{
    protected array $data;

    public function __construct(array $data)
    {
        $this->data = $data;
    }

    public function title(): string
    {
        return 'KPI Summary';
    }

    public function array(): array
    {
        $kpi = $this->data['kpi'] ?? [];

        return [
            ['IRMSystem - Complete Report'],
            ['Period', $this->data['date_from'] . ' to ' . $this->data['date_to']],
            ['Department', $this->data['department_name']],
            ['Generated', $this->data['generated_at']],
            ['Generated By', $this->data['generated_by']],
            $this->data['is_restricted'] ? ['Note', 'Restricted to your department'] : ['', ''],
            [''],
            ['KPI METRICS'],
            ['Metric', 'Value'],
            ['Total Incidents', $kpi['total_incidents'] ?? 0],
            ['Open Incidents', $kpi['open_incidents'] ?? 0],
            ['In Progress', $kpi['in_progress_incidents'] ?? 0],
            ['Resolved', $kpi['resolved_incidents'] ?? 0],
            ['Closed', $kpi['closed_incidents'] ?? 0],
            ['Escalated', $kpi['escalated_incidents'] ?? 0],
            ['Rejected', $kpi['rejected_incidents'] ?? 0],
            ['SLA Breaches', $kpi['sla_breaches'] ?? 0],
            ['SLA Compliance %', ($kpi['sla_compliance'] ?? 0) . '%'],
            ['Resolution Rate %', ($kpi['resolution_rate'] ?? 0) . '%'],
            ['Escalation Rate %', ($kpi['escalation_rate'] ?? 0) . '%'],
            ['Avg Response Time (min)', $kpi['avg_response_time'] ?? 0],
            ['Avg Resolution Time (min)', $kpi['avg_resolution_time'] ?? 0],
        ];
    }

    public function styles(Worksheet $sheet)
    {
        return [
            1 => [
                'font' => ['bold' => true, 'size' => 14, 'color' => ['rgb' => 'FFFFFF']],
                'fill' => [
                    'fillType' => Fill::FILL_SOLID,
                    'startColor' => ['rgb' => '2563EB'],
                ],
            ],
            8 => [
                'font' => ['bold' => true, 'size' => 12],
                'fill' => [
                    'fillType' => Fill::FILL_SOLID,
                    'startColor' => ['rgb' => 'DBEAFE'],
                ],
            ],
            9 => [
                'font' => ['bold' => true],
                'fill' => [
                    'fillType' => Fill::FILL_SOLID,
                    'startColor' => ['rgb' => 'E5E7EB'],
                ],
            ],
        ];
    }
}